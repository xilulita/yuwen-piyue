def g_xingjin(rng):
    a, b, wa, wb = rng.choice(XINGJIN)
    # 挖掉词中易混字，让学生选填
    if rng.random() < 0.5:
        stem = f"选字填空（{a} / {b}）：{wa.replace(a, '（　）')}"
        ans = a
    else:
        stem = f"选字填空（{a} / {b}）：{wb.replace(b, '（　）')}"
        ans = b
    return stem, ans

